compat_dir_t *compat_dir_open(const char *path)
{
    compat_dir_t *directory;
    char manifest_path[512];

    if (snprintf(manifest_path, sizeof(manifest_path), "%s/.compat-dir",
                 path) < 0) {
        return NULL;
    }
    directory = (compat_dir_t *)malloc(sizeof(compat_dir_t));
    if (directory == NULL) {
        return NULL;
    }
    directory->manifest = fopen(manifest_path, "rb");
    if (directory->manifest == NULL) {
        free(directory);
        return NULL;
    }
    return directory;
}

const char *compat_dir_read(compat_dir_t *directory)
{
    size_t length;
    if (directory == NULL || directory->manifest == NULL) {
        return NULL;
    }
    while (fgets(directory->entry, sizeof(directory->entry),
                 directory->manifest) != NULL) {
        length = strlen(directory->entry);
        while (length > 0 &&
               (directory->entry[length - 1] == '\n' ||
                directory->entry[length - 1] == '\r')) {
            directory->entry[--length] = '\0';
        }
        if (length != 0) {
            return directory->entry;
        }
    }
    return NULL;
}

void compat_dir_close(compat_dir_t *directory)
{
    if (directory != NULL) {
        if (directory->manifest != NULL) {
            fclose(directory->manifest);
        }
        free(directory);
    }
}

uint32_t compat_ticks_ms(void)
{
    return (uint32_t)(stub_clock_us() / 1000ULL);
}

uint64_t compat_ticks_us(void)
{
    return stub_clock_us();
}

void compat_delay_ms(uint32_t milliseconds)
{
    /* ISO C has no sleep, so spin on clock(). Unreachable from the
       deterministic replay path, which is how both runners drive the game. */
    const uint64_t target = stub_clock_us() +
                            (uint64_t)milliseconds * 1000ULL;
    while (stub_clock_us() < target) {
    }
}

