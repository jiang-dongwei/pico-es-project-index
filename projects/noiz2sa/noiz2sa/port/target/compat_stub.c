int compat_path_exists(const char *path)
{
    FILE *probe = fopen(path, "rb");
    if (probe == NULL) {
        return 0;
    }
    fclose(probe);
    return 1;
}

compat_path_type_t compat_path_type(const char *path)
{
    /* Files only; see the struct compat_dir comment above. */
    return compat_path_exists(path) ? COMPAT_PATH_FILE : COMPAT_PATH_MISSING;
}

