/* ISO C has no directory API.  The structural probe therefore reads a
   per-directory .compat-dir manifest generated by its test fixture.  This
   exercises the engine's compat_dir_* route without importing a host API;
   the real S17-D backend replaces this with FatFS enumeration. */
struct compat_dir {
    FILE *manifest;
    char entry[256];
};

static compat_pixel_t g_pixels[COMPAT_SCREEN_WIDTH * COMPAT_SCREEN_HEIGHT];
static compat_framebuffer_t g_framebuffer = {
    g_pixels,
    COMPAT_SCREEN_WIDTH,
    COMPAT_SCREEN_WIDTH,
    COMPAT_SCREEN_HEIGHT,
};

/* clock() is ISO C and monotonic for the single-threaded engine loop. It is
   never read on the deterministic replay path (the shim advances a virtual
   tick source instead); the S17-D backend replaces this with the Pico
   microsecond timer. Multiply before dividing so CLOCKS_PER_SEC coarser
   than 1 us does not truncate. */
static uint64_t stub_clock_us(void)
{
    return (uint64_t)clock() * 1000000ULL / (uint64_t)CLOCKS_PER_SEC;
}

