/*
 * Host-OS-free compat v1 backend for the noiz2sa port (S17-D boundary probe).
 *
 * noiz2sa_game is the archive an RP2350B build links unchanged, so "the game
 * layer is reusable" is only worth something if something checks it. This
 * file implements the compat.h contract with ISO C alone -- no <windows.h>,
 * no <dirent.h>, no <sys/stat.h>, no <unistd.h>, no POSIX clock -- and it
 * depends on nothing but compat v1: not the engine headers, not the port
 * headers. CMake enforces that by linking only retropicoes_compat_v1.
 *
 * scripts/test-target-boundary.ps1 links it in place of
 * noiz2sa_host_backend. A link error there means the game archive leaked a
 * host dependency; a framebuffer digest that differs from the host runner's
 * means the backend swap changed behaviour.
 *
 * Scope: a structural probe, not a target backend. The real S17-D
 * FatFS/HSTX/HDMI backend also lives in port/target/.
 */
#include "compat.h"

