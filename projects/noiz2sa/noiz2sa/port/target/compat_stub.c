compat_file_t *compat_file_open(const char *path, const char *mode)
{
    compat_file_t *file = (compat_file_t *)malloc(sizeof(compat_file_t));
    if (file == NULL) {
        return NULL;
    }
    file->stream = fopen(path, mode);
    if (file->stream == NULL) {
        free(file);
        return NULL;
    }
    return file;
}

